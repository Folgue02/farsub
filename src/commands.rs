pub fn name(cmd: Command) -> &'static str {
    COMMANDS
        .iter()
        .find(|c| c.0 == cmd)
        .map(|c| c.1)
        .unwrap_or("?")
}

/// Stable id used in keymap.toml / menus.toml, e.g. `GotoFile` → "goto_file".
pub fn id(cmd: Command) -> String {
    let mut out = String::new();
    for (i, c) in format!("{cmd:?}").chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// The find panel's commands (they also work while it has focus).
pub fn is_find_command(c: Command) -> bool {
    use Command::*;
    matches!(
        c,
        Find | Replace
            | FindInFiles
            | FindNext
            | FindPrev
            | ReplaceNext
            | ReplaceAll
            | FindAll
            | NextResult
            | PrevResult
            | ToggleFindRegex
            | ToggleFindCase
            | ToggleFindWord
            | ToggleFindWrap
            | ToggleFindInSelection
            | ToggleFindContext
    )
}

pub fn from_id(s: &str) -> Option<Command> {
    COMMANDS.iter().map(|c| c.0).find(|c| id(*c) == s)
}
